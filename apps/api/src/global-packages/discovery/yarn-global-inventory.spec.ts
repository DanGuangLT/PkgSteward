import 'reflect-metadata';
import { win32 } from 'node:path';
import { readYarnGlobalInventory } from '@/global-packages/discovery/yarn-global-inventory';
import {
  expectGlobalReason,
  memoryFs,
  testSpawn,
} from '@/global-packages/__fixtures__/global-adapters';
import {
  YARN_TEST_PATHS as Y,
  yarnConfigFacts,
  yarnLocation,
} from '@/global-packages/__fixtures__/yarn1/facts';
import {
  yarnGlobalBinShims,
  yarnLocalBinShims,
} from '@/global-packages/__fixtures__/yarn1/shims';

describe('readYarnGlobalInventory', () => {
  const signal = new AbortController().signal;
  const globalDotBin = win32.join(Y.root, '.bin');

  const seedSemverAndIsOdd = (mem: ReturnType<typeof memoryFs>) => {
    mem.put(Y.global, { directory: true });
    mem.put(Y.root, { directory: true });
    mem.put(Y.bin, { directory: true });
    mem.put(globalDotBin, { directory: true });
    mem.put(win32.join(Y.global, 'package.json'), {
      text: JSON.stringify({
        dependencies: {
          semver: '7.7.1',
          'is-odd': '3.0.0',
          '@types/is-odd': '3.0.0',
        },
      }),
    });
    mem.put(win32.join(Y.global, 'yarn.lock'), {
      text: [
        '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.',
        '# yarn lockfile v1',
        '',
        '"@types/is-odd@3.0.0":',
        '  version "3.0.0"',
        '  resolved "https://registry.yarnpkg.com/@types/is-odd/-/is-odd-3.0.0.tgz#aaaa"',
        '  integrity sha512-typesisodd==',
        '',
        'is-odd@3.0.0:',
        '  version "3.0.0"',
        '  resolved "https://registry.yarnpkg.com/is-odd/-/is-odd-3.0.0.tgz#bbbb"',
        '  integrity sha512-isodd==',
        '',
        'semver@7.7.1:',
        '  version "7.7.1"',
        '  resolved "https://registry.yarnpkg.com/semver/-/semver-7.7.1.tgz#abd5098d82b18c6c81f6074ff2647fd3e7220c9f"',
        '  integrity sha512-semver==',
        '',
      ].join('\n'),
    });

    const semverTarget = win32.join(Y.root, 'semver', 'bin', 'semver.js');
    mem.put(win32.join(Y.root, 'semver', 'package.json'), {
      text: JSON.stringify({
        name: 'semver',
        version: '7.7.1',
        bin: { semver: 'bin/semver.js' },
      }),
    });
    mem.put(semverTarget, { text: '#!/usr/bin/env node\n' });
    mem.put(win32.join(Y.root, 'is-odd', 'package.json'), {
      text: JSON.stringify({ name: 'is-odd', version: '3.0.0' }),
    });
    mem.put(win32.join(Y.root, '@types', 'is-odd', 'package.json'), {
      text: JSON.stringify({ name: '@types/is-odd', version: '3.0.0' }),
    });

    const localShims = yarnLocalBinShims(globalDotBin, 'semver', semverTarget);
    mem.put(localShims.cmdPath, { text: localShims.cmdText });
    mem.put(localShims.shPath, { text: localShims.shText });

    const globalShims = yarnGlobalBinShims(Y.bin, globalDotBin, 'semver');
    mem.put(globalShims.cmdPath, { text: globalShims.cmdText });
    mem.put(globalShims.shPath, { text: globalShims.shText });

    mem.readdir.mockImplementation((dir: string) => {
      const lower = win32.resolve(dir).toLowerCase();
      if (lower === Y.bin.toLowerCase())
        return Promise.resolve(['semver', 'semver.cmd']);
      if (lower === globalDotBin.toLowerCase())
        return Promise.resolve(['semver', 'semver.cmd']);
      return Promise.resolve([]);
    });
  };

  it('returns clean empty inventory without spawning when globalDir or package.json is absent', async () => {
    const mem = memoryFs();
    const spawn = testSpawn();
    const res = await readYarnGlobalInventory(yarnLocation(), {
      fs: mem.fs,
      environment: {},
      signal,
      spawn,
    });
    expect(spawn).not.toHaveBeenCalled();
    expect(res.ownershipComplete).toBe(true);
    expect(res.packages).toEqual([]);
    expect(res.facts).toEqual([]);
    expect(res.yarnInventory?.project.dependencies).toEqual([]);
  });

  it('reads scoped and unscoped manageable packages with registry.yarnpkg.com provenance and 0 spawns', async () => {
    const mem = memoryFs();
    const spawn = testSpawn();
    seedSemverAndIsOdd(mem);
    const res = await readYarnGlobalInventory(yarnLocation(), {
      fs: mem.fs,
      environment: {},
      signal,
      spawn,
    });
    expect(spawn).not.toHaveBeenCalled();
    expect(res.ownershipComplete).toBe(true);
    expect(res.packages).toEqual([
      {
        name: '@types/is-odd',
        version: '3.0.0',
        bins: [],
        status: 'manageable',
        reason: null,
      },
      {
        name: 'is-odd',
        version: '3.0.0',
        bins: [],
        status: 'manageable',
        reason: null,
      },
      {
        name: 'semver',
        version: '7.7.1',
        bins: [{ name: 'semver', target: 'bin/semver.js' }],
        status: 'manageable',
        reason: null,
      },
    ]);
    expect(res.binOwners).toEqual([{ name: 'semver', owner: 'semver' }]);
  });

  it('classifies symlinked yarn-linked package as LINKED_PACKAGE without reading outside targets', async () => {
    const mem = memoryFs();
    seedSemverAndIsOdd(mem);
    mem.put(win32.join(Y.global, 'package.json'), {
      text: JSON.stringify({
        dependencies: {
          semver: '7.7.1',
          'linked-cli': '^1.0.0',
        },
      }),
    });
    mem.put(win32.join(Y.root, 'linked-cli'), {
      link: true,
      real: 'D:\\TEST\\external\\linked-cli',
    });
    const res = await readYarnGlobalInventory(yarnLocation(), {
      fs: mem.fs,
      environment: {},
      signal,
      spawn: testSpawn(),
    });
    const linked = res.packages.find((p) => p.name === 'linked-cli');
    expect(linked).toMatchObject({
      name: 'linked-cli',
      status: 'linked',
      reason: 'LINKED_PACKAGE',
    });
    expect(res.packages.find((p) => p.name === 'semver')?.status).toBe(
      'manageable',
    );
  });

  it('safely refuses Berry __metadata lockfiles and handles unclosed-quote yarn.lock without OOM', async () => {
    const berry = memoryFs();
    seedSemverAndIsOdd(berry);
    berry.put(win32.join(Y.global, 'yarn.lock'), {
      text: '__metadata:\n  version: 8\nsemver@7.7.1:\n  version: 7.7.1\n',
    });
    await expectGlobalReason(
      () =>
        readYarnGlobalInventory(yarnLocation(), {
          fs: berry.fs,
          environment: {},
          signal,
          spawn: testSpawn(),
        }),
      'INVENTORY_FAILED',
    );

    const malformed = memoryFs();
    seedSemverAndIsOdd(malformed);
    malformed.put(win32.join(Y.global, 'yarn.lock'), {
      text: 'semver@7.7.1:\n  version "7.7.1',
    });
    await expectGlobalReason(
      () =>
        readYarnGlobalInventory(yarnLocation(), {
          fs: malformed.fs,
          environment: {},
          signal,
          spawn: testSpawn(),
        }),
      'INVENTORY_FAILED',
    );
  });

  it('marks protected yarn package and unowned colliding shims safely', async () => {
    const mem = memoryFs();
    seedSemverAndIsOdd(mem);
    // Forge global semver.cmd to point outside globalDir
    mem.put(win32.join(Y.bin, 'semver.cmd'), {
      text: '@"C:\\evil\\semver.cmd"   %*\r\n',
    });
    const forgedRes = await readYarnGlobalInventory(yarnLocation(), {
      fs: mem.fs,
      environment: {},
      signal,
      spawn: testSpawn(),
    });
    expect(forgedRes.packages.find((p) => p.name === 'semver')).toMatchObject({
      status: 'invalid',
      reason: 'BIN_CONFLICT',
    });
    expect(
      forgedRes.binOwners.find((b) => b.name === 'semver')?.owner,
    ).toBeNull();

    // Protected package ('yarn' listed directly in global dependencies)
    const protMem = memoryFs();
    seedSemverAndIsOdd(protMem);
    protMem.put(win32.join(Y.global, 'package.json'), {
      text: JSON.stringify({ dependencies: { yarn: '1.22.22' } }),
    });
    protMem.put(win32.join(Y.global, 'yarn.lock'), {
      text: [
        'yarn@1.22.22:',
        '  version "1.22.22"',
        '  resolved "https://registry.yarnpkg.com/yarn/-/yarn-1.22.22.tgz#aaaa"',
        '  integrity sha512-yarn==',
      ].join('\n'),
    });
    protMem.put(win32.join(Y.root, 'yarn', 'package.json'), {
      text: JSON.stringify({
        name: 'yarn',
        version: '1.22.22',
        bin: { yarn: 'bin/yarn.js' },
      }),
    });
    protMem.put(win32.join(Y.root, 'yarn', 'bin', 'yarn.js'), { text: '//y' });
    const lYarn = yarnLocalBinShims(
      globalDotBin,
      'yarn',
      win32.join(Y.root, 'yarn', 'bin', 'yarn.js'),
    );
    const gYarn = yarnGlobalBinShims(Y.bin, globalDotBin, 'yarn');
    protMem.put(lYarn.cmdPath, { text: lYarn.cmdText });
    protMem.put(lYarn.shPath, { text: lYarn.shText });
    protMem.put(gYarn.cmdPath, { text: gYarn.cmdText });
    protMem.put(gYarn.shPath, { text: gYarn.shText });
    protMem.readdir.mockResolvedValue(['yarn', 'yarn.cmd']);

    const protRes = await readYarnGlobalInventory(
      yarnLocation(yarnConfigFacts()),
      { fs: protMem.fs, environment: {}, signal, spawn: testSpawn() },
    );
    expect(protRes.packages[0]).toMatchObject({
      name: 'yarn',
      status: 'protected',
      reason: 'PROTECTED_PACKAGE',
    });
  });

  it('lists npm: alias specs read-only as LINKED_PACKAGE and rejects rogue node.exe in local .bin', async () => {
    const aliasMem = memoryFs();
    seedSemverAndIsOdd(aliasMem);
    aliasMem.put(win32.join(Y.root, 'my-odd'), { directory: true });
    aliasMem.put(win32.join(Y.global, 'package.json'), {
      text: JSON.stringify({
        dependencies: {
          semver: '7.7.1',
          'my-odd': 'npm:is-odd@3.0.0',
        },
      }),
    });
    const aliasRes = await readYarnGlobalInventory(yarnLocation(), {
      fs: aliasMem.fs,
      environment: {},
      signal,
      spawn: testSpawn(),
    });
    expect(aliasRes.packages.find((p) => p.name === 'my-odd')).toMatchObject({
      name: 'my-odd',
      status: 'linked',
      reason: 'LINKED_PACKAGE',
    });
    expect(aliasRes.packages.find((p) => p.name === 'semver')?.status).toBe(
      'manageable',
    );

    const rogueMem = memoryFs();
    seedSemverAndIsOdd(rogueMem);
    rogueMem.put(win32.join(globalDotBin, 'node.exe'), { text: 'EVIL' });
    rogueMem.readdir.mockImplementation((dir: string) => {
      const lower = win32.resolve(dir).toLowerCase();
      if (lower === Y.bin.toLowerCase())
        return Promise.resolve(['semver', 'semver.cmd']);
      if (lower === globalDotBin.toLowerCase())
        return Promise.resolve(['node.exe', 'semver', 'semver.cmd']);
      return Promise.resolve([]);
    });
    const rogueRes = await readYarnGlobalInventory(yarnLocation(), {
      fs: rogueMem.fs,
      environment: {},
      signal,
      spawn: testSpawn(),
    });
    expect(rogueRes.ownershipComplete).toBe(false);
    expect(rogueRes.packages.find((p) => p.name === 'semver')).toMatchObject({
      status: 'invalid',
      reason: 'BIN_CONFLICT',
    });
  });
});
