#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md at the repository root from `pnpm licenses list --prod --json`
// of each app. Run from anywhere after installing both apps: node scripts/third-party-notices.mjs
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const apps = [
  { name: '@pkgsteward/api', dir: 'apps/api' },
  { name: '@pkgsteward/web', dir: 'apps/web' },
];

const PERMISSIVE = new Set(['MIT', 'ISC', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD']);

// Notes for licenses outside the permissive set above; the first matching rule wins.
const ATTENTION_NOTES = [
  [/LGPL/, 'Contains LGPL-3.0-or-later code (libvips, loaded dynamically by sharp). A bundled release must ship the LGPL text and keep the library replaceable.'],
  [/CC-BY-4\.0/, 'Data under CC BY 4.0: keep the attribution (author, source and license) in every redistribution.'],
  [/PSF-2\.0/, 'Python Software Foundation License 2.0 (permissive): keep the copyright notice and the license text.'],
  [/BlueOak-1\.0\.0/, 'Blue Oak Model License 1.0.0 (permissive): keep the license text.'],
  [/ OR /, 'Dual license: either may be chosen; PkgSteward uses the package under the first one listed.'],
  [/ AND /, 'Every listed license applies: keep each notice.'],
];

const listLicenses = (dir) => {
  // Constant command, no user input: shell is only needed to resolve pnpm.cmd on Windows.
  const out = execSync('pnpm licenses list --prod --json', {
    cwd: join(root, dir),
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
    maxBuffer: 64 * 1024 * 1024,
  });
  return JSON.parse(out);
};

const cell = (value) => String(value ?? '').replace(/\|/g, '\\|').trim();
// Keep the author's name only: drop "<email>" and "(url)" parts.
const authorName = (author) => cell(String(author ?? '').replace(/<[^>]*>|\([^)]*\)/g, '')) || '—';
const homepage = (pkg) => pkg.homepage || `https://www.npmjs.com/package/${pkg.name}`;
const byName = (a, b) => a.name.localeCompare(b.name, 'en');

const lines = [
  '# Third-party notices',
  '',
  'PkgSteward is Copyright (c) 2026 LianHarman (LienThuan04), licensed under the [MIT License](LICENSE).',
  '',
  'PkgSteward depends on the open-source packages listed below. Each package is the work of its own',
  'authors and is used under its own license; the copyright in each package belongs to its authors,',
  'not to PkgSteward.',
  '',
  'The list covers production dependencies only (`pnpm licenses list --prod`), as installed on Windows.',
  'Platform-specific packages (for example `@img/sharp-win32-x64`) differ on other systems. A release that',
  'bundles these packages must ship their full license texts and any Apache-2.0 `NOTICE` files.',
  '',
  'Generated by `node scripts/third-party-notices.mjs`; regenerate it after any dependency change.',
];

const attention = [];
const sections = [];

for (const app of apps) {
  const groups = Object.entries(listLicenses(app.dir))
    .map(([license, pkgs]) => ({ license, pkgs: [...pkgs].sort(byName) }))
    .sort((a, b) => b.pkgs.length - a.pkgs.length || a.license.localeCompare(b.license, 'en'));
  const total = groups.reduce((sum, g) => sum + g.pkgs.length, 0);

  sections.push('', `## ${app.name} (\`${app.dir}\`)`, '', `${total} packages.`);
  for (const { license, pkgs } of groups) {
    sections.push('', `### ${license} (${pkgs.length})`, '', '| Package | Version | Author | Homepage |', '|---|---|---|---|');
    for (const pkg of pkgs) {
      sections.push(`| ${cell(pkg.name)} | ${cell(pkg.versions.join(', '))} | ${authorName(pkg.author)} | ${cell(homepage(pkg))} |`);
    }
    if (!PERMISSIVE.has(license)) {
      const note = ATTENTION_NOTES.find(([pattern]) => pattern.test(license))?.[1] ?? 'Not a common permissive license: review it before a release.';
      for (const pkg of pkgs) {
        attention.push(`| ${cell(pkg.name)} | ${cell(pkg.versions.join(', '))} | ${app.name} | ${cell(license)} | ${note} |`);
      }
    }
  }
}

if (attention.length > 0) {
  lines.push('', '## Needs attention', '', '| Package | Version | App | License | Note |', '|---|---|---|---|---|', ...attention);
}
lines.push(...sections, '');

writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), lines.join('\n'));
console.log(`THIRD_PARTY_NOTICES.md written (${attention.length} packages need attention).`);
